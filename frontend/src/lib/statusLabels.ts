export function statusLabel(code: string | null | undefined, locale: Locale): string {
  const label = code && Object.hasOwn(labels, code) ? labels[code] : null;
  return label?.[locale === 'vi' ? 0 : 1] ?? (locale === 'vi' ? 'Chưa xác định' : 'Unknown');
}
